def format_changelog(limit: int = 3) -> str:
    lines = [f"── Что нового (сейчас {VERSION}) ──", ""]
    for ver, items in CHANGELOG[:limit]:
        lines.append(f"<b>{ver}</b>")
        for it in items:
            lines.append(f"  • {it}")
        lines.append("")
    lines.append("Команды: /help · /start · /export · факт")
    return "\n".join(lines)
