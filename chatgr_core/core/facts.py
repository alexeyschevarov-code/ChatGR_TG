def fact_for(topic: str | None = None, day: date | None = None) -> str:
    day = day or date.today()
    key = topic if topic in FACTS else "default"
    pool = FACTS[key]
    h = hashlib.md5(f"{day.isoformat()}:{key}".encode()).hexdigest()
    idx = int(h[:8], 16) % len(pool)
    return pool[idx]


def format_daily_fact(topic: str | None = None) -> str:
    f = fact_for(topic)
    label = topic or "общее"
    return f"── Факт дня ({label}) ──\n{f}"
